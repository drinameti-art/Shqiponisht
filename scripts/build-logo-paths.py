#!/usr/bin/env python3
"""Traces assets/images/logo-mark.png into SVG paths for the animated logo intro.

Writes src/data/logo-paths.generated.ts. Needs: pip install opencv-python-headless numpy pillow.
Usage: python3 scripts/build-logo-paths.py
"""
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
im = np.array(Image.open(ROOT / 'assets/images/logo-mark.png').convert('RGBA')).astype(int)
r, g, b, a = im[..., 0], im[..., 1], im[..., 2], im[..., 3]
H, W = r.shape
masks = {
    'red': (a > 128) & (r > 160) & (g < 110) & (b < 110),
    'black': (a > 128) & (r < 90) & (g < 90) & (b < 90),
    'cream': (a > 128) & (r > 200) & (g > 190) & (b > 160),
}


def paths(mask: np.ndarray, eps: float = 0.9) -> list[tuple[str, tuple[int, int, int, int], float]]:
    """Outer contours (with their holes) as SVG path strings, bounding box and outline length."""
    m = cv2.morphologyEx(mask.astype(np.uint8) * 255, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))
    contours, hier = cv2.findContours(m, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    out = []
    if hier is None:
        return out
    for i, c in enumerate(contours):
        if hier[0][i][3] != -1 or cv2.contourArea(c) < 40:
            continue
        rings = [c] + [contours[j] for j in range(len(contours)) if hier[0][j][3] == i and cv2.contourArea(contours[j]) > 20]
        d = ''
        for ring in rings:
            pts = cv2.approxPolyDP(ring, eps, True).reshape(-1, 2)
            d += 'M' + ' L'.join(f'{x} {y}' for x, y in pts) + ' Z '
        out.append((d.strip(), cv2.boundingRect(c), float(cv2.arcLength(c, True))))
    return out


red = paths(masks['red'])
black = paths(masks['black'])
cream = paths(masks['cream'])

top_beam = [p for p in red if p[1][1] < 70 and p[1][3] < 60]

# The gate in separate pieces, so the intro can build it like the reel:
# pillars grow from their feet, the tie beam slides in, the centre post drops.
ys, xs = np.mgrid[0:H, 0:W]
gate_mask = masks['red'] & (ys >= 105)
def piece(cond):
    found = paths(gate_mask & cond)
    return max(found, key=lambda p: p[1][2] * p[1][3])[0]

def pillar(x0, x1):
    # Where the tie beam crosses, keep only the pillar's own width (taken from the rows just below).
    band = gate_mask & (xs >= x0) & (xs <= x1)
    below = np.nonzero(band[232])[0]
    m = band.copy()
    m[166:232] = False
    m[166:232, below.min():below.max() + 1] = True
    found = paths(m)
    return max(found, key=lambda p: p[1][2] * p[1][3])[0]

LEFT_PILLAR = pillar(185, 270)
RIGHT_PILLAR = pillar(630, 715)
TIE = piece((ys >= 170) & (ys <= 228))
POST = piece((xs > W * 0.42) & (xs < W * 0.58) & (ys < 178))
gate = [p for p in red if p not in top_beam]
feet = sorted((p for p in black if p[1][1] > 580), key=lambda p: p[1][0])  # left foot first
beam = [p for p in black if p[1][1] < 120 and p[1][2] > 400]
kosovo = max((p for p in black if p not in feet and p not in beam), key=lambda p: p[1][2] * p[1][3])
stars = sorted((p for p in cream if p[1][1] < 115 and p[1][2] < 40), key=lambda p: p[1][0])
plaques = [p for p in cream if p not in stars]

def ts(name: str, items: list) -> str:
    return f'export const {name} = {[i[0] for i in items]!r};'.replace("'", "'")

lines = [
    '// Generated by scripts/build-logo-paths.py from assets/images/logo-mark.png. Do not edit by hand.',
    f'export const LOGO_VIEWBOX = {{ width: {W}, height: {H} }};',
    ts('TOP_BEAM', top_beam),
    ts('GATE', gate),
    ts('FEET', feet),
    ts('BEAM', beam),
    f"/** The black beam without its star holes (the stars arrive later in the intro). */",
    f"export const BEAM_SOLID = {beam[0][0].split(' Z ')[0] + ' Z'!r};",
    ts('STARS', stars),
    ts('PLAQUES', plaques),
    f"export const LEFT_PILLAR = {LEFT_PILLAR!r};",
    f"export const RIGHT_PILLAR = {RIGHT_PILLAR!r};",
    f"export const TIE = {TIE!r};",
    f"export const POST = {POST!r};",
    f"export const KOSOVO = {kosovo[0]!r};",
    f"/** Bounding box of KOSOVO: x, y, width, height. */",
    f"export const KOSOVO_BOX = {list(kosovo[1])};",
    f'/** Outline length of KOSOVO, for drawing it stroke by stroke. */',
    f'export const KOSOVO_LENGTH = {round(kosovo[2])};',
]
(ROOT / 'src/data/logo-paths.generated.ts').write_text('\n'.join(lines) + '\n', 'utf-8')
print({k: len(v) for k, v in dict(top_beam=top_beam, gate=gate, feet=feet, beam=beam, stars=stars, plaques=plaques).items()}, 'kosovo', kosovo[1])
